"""투자 셈 — 사는 셈(`buy`)과 짓는 셈(`build`). 정본 아티팩트 「모델용 투자 셈」.

**값을 지어내지 않는다.** 금리도 임대료도 공사단가도 기본값이 없다. 모르면 받는다.
받은 것이 우리 추정이면 부르는 이름이 달라진다(`추정` 접두) — 레버리지가 오차를 키우기
때문이다. 임대 추정 오차 28.8% 가 자기자본 수익률에서 58% 로 불어난다(2026-09-24).

**판단은 안 한다.** 「사업성이 좋다」는 말을 여기서 내지 않고 숫자만 낸다.

여기 셈은 매수자 모달의 투자 시뮬(0133, `UnifiedBuyerModal.tsx`)과 **같아야 한다.**
지금은 같은 산식이 TSX 와 파이썬 두 곳에 산다. 화면이 API 를 부르게 바꾸면 한 곳이 된다(할일).
"""
from __future__ import annotations

M2_PER_PY = 3.305785           # ㎡ → 평은 나누기, 평 → ㎡ 는 곱하기
FEE_PCT_DEFAULT = 5.7          # 부대비용률 — 화면 기본값과 같아야 한다
DEV_FEE_PCT_DEFAULT = 10.0     # 신축 부대비용률(설계·감리·인허가)


def _py(m2: float) -> float:
    return m2 / M2_PER_PY


def buy(*, 거래금액: float, 자기자본: float, 금리: float, 연임대료: float,
        부대비용률: float | None = None) -> dict[str, float | None]:
    """사는 셈. 한 해짜리다 — 상환 스케줄이 없어 원리금·연 환산 수익률은 안 낸다.

    대출 비율은 **거래금액**으로 나눈다. 총투자비로 나누면 은행이 말하는 것과 달라진다.
    """
    fee_pct = FEE_PCT_DEFAULT if 부대비용률 is None else 부대비용률
    부대비용 = round(거래금액 * fee_pct / 100)
    총투자비 = round(거래금액 + 부대비용)
    대출 = max(0, 총투자비 - round(자기자본))
    연이자 = round(대출 * 금리 / 100)
    연순수익 = round(연임대료 - 연이자)
    return {
        "부대비용": 부대비용,
        "총투자비": 총투자비,
        "대출": 대출,
        "대출 비율": round(대출 / 거래금액 * 100, 1) if 대출 and 거래금액 else None,
        "연 이자": 연이자,
        "연 순수익": 연순수익,
        "자기자본 수익률": round(연순수익 / 자기자본 * 100, 1) if 자기자본 > 0 else None,
        # 대출이 없으면 0 으로 나누지 않고 **칸을 비운다.** 미지정은 null 이지 무한대가 아니다
        "이자 대비 임대료": round(연임대료 / 연이자, 2) if 연이자 > 0 else None,
        # 공실이 이만큼 나면 순수익이 0 이 된다
        "손익분기 공실률": round(연순수익 / 연임대료 * 100, 1) if 연임대료 > 0 else None,
    }


def build(*, 대지면적: float, 법정용적률: float, 법정건폐율: float | None, 거래금액: float,
          추정공사단가: float, 추정완성단가: float,
          부대비용률: float | None = None) -> dict[str, float | None]:
    """짓는 셈. 단가 둘은 **원/평**이고 면적은 ㎡ 로 받아 평으로 고쳐 곱한다.

    법정 연면적은 **지상 기준**이다. 지하는 용적률에 안 들어가 실제론 더 지을 수 있는데,
    지하는 단가가 따로라 1차에선 안 센다.
    """
    fee_pct = DEV_FEE_PCT_DEFAULT if 부대비용률 is None else 부대비용률
    연면적 = 대지면적 * 법정용적률 / 100
    건축면적 = 대지면적 * 법정건폐율 / 100 if 법정건폐율 else None
    공사비 = round(_py(연면적) * 추정공사단가)
    부대비용 = round(공사비 * fee_pct / 100)
    총사업비 = round(거래금액 + 공사비 + 부대비용)
    완성가치 = round(_py(연면적) * 추정완성단가)
    개발이익 = 완성가치 - 총사업비
    return {
        "법정 연면적": round(연면적, 1),
        "법정 건축면적": round(건축면적, 1) if 건축면적 else None,
        # 건축면적이 없으면 층수를 못 낸다. 지어내지 않는다
        "층수": int(연면적 // 건축면적) if 건축면적 else None,
        "추정 공사비": 공사비,
        "추정 부대비용": 부대비용,
        "추정 총사업비": 총사업비,
        "추정 완성가치": 완성가치,
        "추정 개발이익": 개발이익,
        "추정 개발이익률": round(개발이익 / 총사업비 * 100, 1) if 총사업비 > 0 else None,
        # **이 땅에 얼마까지 낼 수 있나.** 거래금액과 견주면 싼지 비싼지가 나온다(판단은 안 한다)
        "추정 토지잔여가치": 완성가치 - 공사비 - 부대비용,
    }
