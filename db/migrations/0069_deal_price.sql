-- 0069 · 거래가 — 계약으로 합의된 값
--
-- 매매가(내놓은 값)·매도희망가(받고 싶은 값)·매수희망가(사고 싶은 값)는 협상 중의 값이고,
-- 거래가는 **합의된 사실**이다. 성격이 달라 따로 든다. 예상 수수료(거래가×0.9%)의 기준값.
--
-- 자리 = 관계(proposals). 계약은 특정 매수자와의 합의라 매수자×매물에 붙는다 —
-- 계약파기 후 다른 매수자와 재계약하면 관계마다 값이 다르다. 매물 단위 거래가는
-- 「계약(·계약파기) 상태인 제안의 deal_price」로 파생한다(프로필-커밋.md 가격 원칙 그대로).

