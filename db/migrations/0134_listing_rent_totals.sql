-- 총보증금·총임대료·총관리비(2026-08-27) — 임대 총계의 **정본 칸**.
--
-- 여태 총계는 저장되지 않았다. 층별 실측이 있으면 그 합계, 없으면 **대장 추정으로 메우는**
-- 하이브리드(0030)가 그 자리를 대신했다. 그래서 팀이 한 층만 입력해도 나머지가 추정으로
-- 채워져 수익률이 섰고, 그 값은 실측도 추정도 아닌 잡종이었다.
-- 층별 임대시세를 미리 안 채워두는 원칙과 같은 이유로, 총계도 지어내지 않는다.
--
-- 채우는 길은 둘이다:
--   ① 층별 임대를 넣으면 그 합계가 총값이 된다(일부만 넣었으면 그 일부의 합)
--   ② 층별이 없어도 총값을 직접 적을 수 있다 — 중개인은 대개 총액을 먼저 안다
-- 둘 다 있으면 **층별이 이긴다**. 두 값이 동시에 살아 있으면 어느 게 진짜인지 모르게 된다.
--
-- 단위는 원. 미지정은 null — 0과 다르다(0은 「안 받는다」, null은 「모른다」).
ALTER TABLE app.listings
  ADD COLUMN IF NOT EXISTS total_deposit bigint,   -- 총보증금(원)
  ADD COLUMN IF NOT EXISTS total_rent    bigint,   -- 총월임대료(원)
  ADD COLUMN IF NOT EXISTS total_mgmt    bigint;   -- 총월관리비(원)
