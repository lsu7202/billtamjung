-- 0143 · 검색 전용 계산값 — 대장이 0으로 준 용적률·건폐율을 채운다 (2026-08-30)
--
-- ## 왜 표를 따로 두나
--
-- **우리 데이터는 건축물대장과 일치해야 한다.** 화면에 보이는 값이 그대로 계약서·중개대상물
-- 확인설명서·브리핑 자료로 이어진다. 대장에 없는 값을 우리가 채워 보여주면 그 서류가 틀린다.
--
-- 그런데 검색은 사정이 다르다. 지금 용적률로 거르면 **89,418동(15.3%)이 통째로 사라진다.**
-- 「여유 용적률」로 신축 부지를 찾는 필터가 정작 옛 저층 건물을 빠뜨린다 — 가장 유망한 물건들이다.
--
-- 그래서 **거르는 값과 보여주는 값을 갈라 놓는다.** 이 표는 검색만 읽는다.
-- master.buildings 는 대장 그대로다.
--
-- ## 대장이 0인 이유 (조사 2026-08-30)
--
-- 원천 표제부에 **빈 칸은 하나도 없고 전부 명시적 0** 이다(115,543동·19.7%). 누락이 아니다.
--   · 부속건축물 50.5% 가 0 — 정상이다. 대지·건폐율은 그 필지의 주건축물에 붙는다.
--   · 주건축물은 **연식**이다: 사용승인일 없음 42.6% · 1980s 20.6% · 2000s 0.3% · 2010s~ 0.1%.
--     전산화 이전 대장이라 애초에 안 적혔다.
--
-- ## 산식 — 필지 단위 합산
--
-- 용적률·건폐율은 **건물이 아니라 필지의 값**이다. 대장은 그 필지 전체의 값을 각 동에
-- 똑같이 적어 준다. 그래서 한 필지에 여러 동이면 면적을 합쳐야 맞는다.
--   관악구 남현동 1136번지(12동): 한 동만 보면 0.43%, 12동 합치면 205.95% = 대장 값
--
--     용적률 = Σ(그 필지 모든 동의 용적산정면적) ÷ 대지면적 × 100
--     건폐율 = Σ(그 필지 모든 동의 건축면적)     ÷ 대지면적 × 100
--
-- **검산**: 대장에 값이 있는 427,107 필지로 대조 → **99.1% 일치**.
-- 어긋난 0.9%(677필지)는 관악산 산56-1(150동)·경복궁·상계동 단지처럼 한 지번에 수백 동이
-- 묶여 **대장 스스로 동마다 다른 대지면적·용적률을 적어 둔** 곳이다. 우리가 고칠 것이 아니다.
--
-- ## 채워지는 것
--   용적률 18,175동 (복사 4,740 · 계산 13,435) → 커버리지 84.7% → 87.8%
--   건폐율 16,926동 (복사 4,616 · 계산 12,310) → 커버리지 81.5% → 84.4%
--
-- ## 못 채우는 것 — 재료가 없다
--   용적률 71,243동(용적산정면적 0) · 건폐율 91,317동(건축면적 0)
--   건축면적 115,088동 — 층별개요 유추는 0044 에서 ±10% 밖 23.6% 로 이미 기각
--   대지면적 23,155동 — 그중 22,954동은 **연속지적도에 그 PNU 자체가 없다**

BEGIN;

CREATE TABLE IF NOT EXISTS master.building_calc (
  building_pk text PRIMARY KEY,
  far_calc    numeric,        -- 계산 용적률(%). 대장에 값이 있으면 NULL(대장이 이긴다)
  bcr_calc    numeric,        -- 계산 건폐율(%)
  far_src     text,           -- 'parcel_copy'(같은 필지 다른 동의 대장값) | 'computed'(합산 계산)
  bcr_src     text,
  built_at    timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE master.building_calc IS
  '검색 전용 계산값(0143). **사용자에게 보여주지 않는다** — 화면 값은 계약서·확인설명서로
   이어지므로 건축물대장과 일치해야 한다. search.py 의 far·bcr 필터만 이 표를 COALESCE 한다.';
COMMENT ON COLUMN master.building_calc.far_src IS
  'parcel_copy = 같은 필지 다른 동에 대장 용적률이 있어 그대로 옮김(계산 아님)
   computed    = 필지의 용적산정면적 합 ÷ 대지면적. 대장 대조 99.1% 일치';

CREATE INDEX IF NOT EXISTS building_calc_far_idx ON master.building_calc (far_calc) WHERE far_calc IS NOT NULL;
CREATE INDEX IF NOT EXISTS building_calc_bcr_idx ON master.building_calc (bcr_calc) WHERE bcr_calc IS NOT NULL;

COMMIT;
