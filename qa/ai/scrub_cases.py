#!/usr/bin/env python3
"""scrub 회귀 — 지워야 할 것은 지우고, 살려야 할 것은 살리는가. 정본 10-AI-어시스턴트 §18-3

파서 회귀 코퍼스와 같은 어법이다. 못 잡는 문장이 나오면 **여기 넣고** 규칙을 늘린다.
모델도 DB 도 안 부른다. 커밋마다 돈다.

    backend/.venv/bin/python qa/ai/scrub_cases.py
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "backend"))
from app.ai.scrub import scrub  # noqa: E402

# (문장, 지워져야 하는 갈래들, 살아 있어야 하는 조각들)
CASES: list[tuple[str, list[str], list[str]]] = [
    # ── 지워야 한다 ──────────────────────────────────────────────
    ("소유자 김영수 800101-1234567 성수동1가 14-53", ["주민번호"], ["김영수", "성수동1가 14-53"]),
    ("주민번호 800101 1234567", ["주민번호"], []),
    ("8001011234567", ["주민번호"], []),
    ("등기부상 900215-2****** 로 표기", ["주민번호"], ["등기부상"]),
    ("외국인등록번호 850303-5123456", ["주민번호"], ["외국인등록번호"]),
    ("면허 11-23-456789-01 확인함", ["운전면허"], ["확인함"]),
    ("카드 1234-5678-9012-3456 결제", ["카드번호"], ["결제"]),
    ("여권 M12345678 사본", ["여권번호"], ["사본"]),
    ("여권 M123A4567", ["여권번호"], []),
    ("계좌 110-123-456789 국민은행", ["계좌번호"], ["국민은행"]),
    ("농협 352-0123-4567-89", ["계좌번호"], ["농협"]),
    ("김영수 800101-1234567 · 전화 010-1234-5678", ["주민번호"], ["김영수", "010-1234-5678"]),

    # ── 살려야 한다 ──────────────────────────────────────────────
    ("전화 010-1234-5678", [], ["010-1234-5678"]),
    ("사무실 02-555-1234", [], ["02-555-1234"]),
    ("02 555 1234 로 연락", [], ["02 555 1234"]),
    ("성수동1가 14-53", [], ["14-53"]),
    ("삼성동 140-3번지 · 140-10번지", [], ["140-3", "140-10"]),
    ("2026-09-08 준공", [], ["2026-09-08"]),
    ("1998년 12월 22일", [], ["1998년 12월 22일"]),
    ("연면적 1,240.5㎡ 대지 661.16㎡", [], ["1,240.5", "661.16"]),
    ("호가 42억 · 공시지가 1,310만원", [], ["42억", "1,310만원"]),
    ("건물 pk 1024123619", [], ["1024123619"]),
    ("PNU 1168010600101400003", [], ["1168010600101400003"]),
    ("고시 제2025-123호", [], ["2025-123"]),
    ("용적률 240% 건폐율 58.3%", [], ["240%", "58.3%"]),
    ("층 5층 지하 2층", [], ["5층", "지하 2층"]),
    ("사업자등록번호 123-45-67890", [], ["123-45-67890"]),   # 사업자번호는 공개 정보. 10자리라 계좌 꼴에 안 걸린다
]


def main() -> int:
    bad = 0
    for text, want_kinds, keep in CASES:
        r = scrub(text)
        got = sorted(set(r.hits))
        problems = []
        for k in want_kinds:
            if k not in r.hits:
                problems.append(f"「{k}」를 못 지웠다")
        if not want_kinds and r.hits:
            problems.append(f"지우면 안 되는데 지웠다 {got}")
        for frag in keep:
            if frag not in r.text:
                problems.append(f"「{frag}」가 살아 있어야 한다")
        if problems:
            bad += 1
            print(f"  ✗ {text}")
            print(f"      → {r.text}")
            for p in problems:
                print(f"      {p}")
        else:
            tag = " · ".join(got) if got else "그대로"
            print(f"  ✓ {text}  →  {tag}")
    print()
    if bad:
        print(f"✗ {bad} / {len(CASES)} 어긋남")
        return 1
    print(f"✓ {len(CASES)}문장 전부 맞음")
    return 0


if __name__ == "__main__":
    sys.exit(main())
